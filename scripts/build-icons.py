#!/usr/bin/env python3
"""Vendors the Phosphor icons the site uses (MIT, https://phosphoricons.com).

    npm pack @phosphor-icons/core && tar xzf phosphor-icons-core-*.tgz
    python3 scripts/build-icons.py path/to/package

Writes assets/icons/<name>.svg, assets/icons/LICENSE and assets/js/data/icons.js
(window.ICONS for scripts). Templates use {{icon:name}} which build-pages.py inlines.
Add a name to ICONS below and re-run to make another icon available.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "icons"

# name used in the site -> (phosphor weight, phosphor file name)
ICONS = {
    "caret-left": ("regular", "caret-left"), "caret-right": ("regular", "caret-right"),
    "caret-down": ("regular", "caret-down"), "caret-up": ("regular", "caret-up"),
    "x": ("regular", "x"), "list": ("regular", "list"),
    "heart": ("regular", "heart"), "heart-fill": ("fill", "heart"),
    "star-fill": ("fill", "star"), "check": ("bold", "check"),
    "magnifying-glass": ("regular", "magnifying-glass"), "user": ("regular", "user"),
    "bag": ("regular", "handbag"), "cart-plus": ("regular", "shopping-cart-simple"),
    "house": ("regular", "house"), "percent": ("regular", "seal-percent"),
    "laptop": ("regular", "laptop"), "recycle": ("regular", "arrows-clockwise"),
    "network": ("regular", "tree-structure"), "cpu": ("regular", "cpu"),
    "buildings": ("regular", "buildings"), "squares": ("regular", "squares-four"),
    "rack": ("regular", "hard-drives"), "mouse": ("regular", "mouse-simple"),
    "map-pin": ("regular", "map-pin"), "phone": ("regular", "phone"),
    "envelope": ("regular", "envelope-simple"), "clock": ("regular", "clock"),
    "shield-check": ("regular", "shield-check"), "headset": ("regular", "headset"),
    "warning": ("regular", "warning"), "package": ("regular", "package"),
    "pause": ("fill", "pause"), "play": ("fill", "play"),
    "check-square": ("regular", "check-square"), "funnel": ("regular", "funnel-simple"),
    "target": ("regular", "target"), "trend-up": ("regular", "trend-up"),
    "factory": ("regular", "factory"), "storefront": ("regular", "storefront"),
    "flask": ("regular", "flask"), "graduation-cap": ("regular", "graduation-cap"),
    "bank": ("regular", "bank"), "layout": ("regular", "layout"),
    "sign-out": ("regular", "sign-out"), "truck": ("regular", "truck"),
    "share": ("regular", "share-network"), "arrow-up": ("regular", "arrow-up"),
    "wifi": ("regular", "wifi-high"), "plugs": ("regular", "plugs-connected"),
    "info": ("regular", "info"), "trash": ("regular", "trash"), "pencil": ("regular", "pencil-simple"),
    "minus": ("bold", "minus"), "plus": ("bold", "plus"), "seal-check": ("regular", "seal-check"),
}


def main():
    pkg = Path(sys.argv[1] if len(sys.argv) > 1 else "package")
    assets = pkg / "assets"
    OUT.mkdir(parents=True, exist_ok=True)
    js = {}
    for name, (weight, file) in ICONS.items():
        suffix = "" if weight == "regular" else "-" + weight
        src = (assets / weight / f"{file}{suffix}.svg").read_text(encoding="utf-8")
        inner = re.search(r"<svg[^>]*>(.*)</svg>", src, re.S).group(1).strip()
        svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="currentColor">{inner}</svg>'
        (OUT / f"{name}.svg").write_text(svg + "\n", encoding="utf-8")
        js[name] = inner
    license_src = pkg / "LICENSE"
    (OUT / "LICENSE").write_text(
        "Icons from Phosphor Icons (https://phosphoricons.com)\n\n" +
        (license_src.read_text(encoding="utf-8") if license_src.exists() else "MIT License"), encoding="utf-8")
    body = json.dumps(js, ensure_ascii=False, indent=0)
    (ROOT / "assets" / "js" / "data" / "icons.js").write_text(
        "/* Generated by scripts/build-icons.py from Phosphor Icons (MIT). Do not edit. */\n"
        "(function () {\n  'use strict';\n  var paths = " + body + ";\n"
        "  /* icon('heart', 'extra-class') -> inline, decorative <svg> string */\n"
        "  window.icon = function (name, cls) {\n"
        "    return '<svg class=\"icon' + (cls ? ' ' + cls : '') + '\" viewBox=\"0 0 256 256\" fill=\"currentColor\" aria-hidden=\"true\" focusable=\"false\">' + (paths[name] || '') + '</svg>';\n"
        "  };\n})();\n", encoding="utf-8")
    print(f"{len(js)} icons")


if __name__ == "__main__":
    main()
