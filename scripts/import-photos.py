#!/usr/bin/env python3
"""Registers real product photos so the site uses them instead of the SVG drawings.

1. Put photos in assets/images/photos/ named by product id, e.g. l01.webp, n03.jpg
   (square, white background, about 1000x1000 px; WebP preferred).
2. Run: python3 scripts/import-photos.py
This writes assets/js/data/photos.js. Products without a photo keep their drawing.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PHOTOS = ROOT / "assets" / "images" / "photos"
EXT = (".webp", ".jpg", ".jpeg", ".png", ".avif")


def main():
    found = {}
    for f in sorted(PHOTOS.iterdir()):
        if f.suffix.lower() in EXT:
            found.setdefault(f.stem, f.name)  # first match wins (sorted: avif < jpg < png < webp)
    out = ROOT / "assets" / "js" / "data" / "photos.js"
    out.write_text("/* Generated by scripts/import-photos.py. Do not edit. */\n"
                   "window.SHOP_PHOTOS = " + json.dumps(found, indent=2) + ";\n", encoding="utf-8")
    print(f"{len(found)} photos registered")


if __name__ == "__main__":
    main()
